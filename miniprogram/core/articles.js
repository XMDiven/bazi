const hideGanTable = () => ZHI_LIST.map(z => `${z}：${LunarUtil.ZHI_HIDE_GAN[z].join('、')}`).join('；');

function naYinTable() {
  const rows = [];
  for (let i = 0; i < JIA_ZI.length; i += 2) {
    rows.push(`${JIA_ZI[i]}、${JIA_ZI[i + 1]}：${LunarUtil.NAYIN[JIA_ZI[i]]}`);
  }
  return rows.join('；');
}

